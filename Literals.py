#Literals: literals are fixed values in a program
#Integer Literal, Float Literal, Complex Literal, String Literal, List Literal, Tuple Literal, Dictionary Literal

#Integer Literal
x = 10
y = -25
z = 0

#Octal Literal
x = 0O34 # 0O or 0o prefix for octal numbers, Here 0O34 is octal representation of decimal 28

#Hexadecimal Literal
x = 0X1C # 0X or 0x prefix for hexadecimal numbers, Here 0X1C is hexadecimal representation of decimal 28

#Float Literal
x = 25.55
y = 0.05
z = -12.2345

#Complex Literal
x = 3.14j
y= 5j

#String Literal
var1 = "Hello"
var2 = "Python"

#List Literal
L1=[1,"Ravi",75.50, True]

#Tuple Literal
T1=(1,"Ravi",75.50, True)

#Dictionary Literal
D1={"Name":"Ravi","Age":25,"Salary":75000.50}